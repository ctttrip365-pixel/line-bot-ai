// lib/chat-filters.ts — ตัดสินว่าข้อความไหน "ไม่ต้องตอบ"
//
// เสียงหัวเราะล้วนๆ (55 / 555 / ๕๕๕ / ฮ่าๆ / ฮ่าฮ่า / 😂 / haha / lol) ไม่ใช่คำถาม — คนจริงไม่ตอบ
// แชมป์สั่ง 8 ต.ค. 2026 หลังเห็นบอทตอบ "55" ด้วยข้อความ "ขออภัยนะครับ ขอเวลาเช็ค…" (เจอในแชททดสอบจริง)
// ข้อความที่มีคำอื่นผสม เช่น "555 ขอบคุณครับ" "ฮ่าๆ แล้วราคาเท่าไหร่" ยังส่งเข้าบอทตามปกติ

const LAUGH_TOKEN = /(?:[5๕]{2,}|(?:ฮ่า|ฮา|ฮ้า|ฮ๊า|ฮ่าฮ่า|หะหะ|ฮิ|อิอิ|ฮ่ะ|แหะ)+ๆ*|(?:ha|he){2,}|ha+h[ah]*|lol+|lmao|rofl|[😂🤣😆😄😁😀😅😹]+|ๆ+)/gi;

export function isLaughterOnly(text: string): boolean {
  const t = text
    .replace(/[\s.,!?~\-_*()[\]"'’“”…]+/g, '')
    .toLowerCase();
  if (!t) return false;
  return t.replace(LAUGH_TOKEN, '') === '';
}
